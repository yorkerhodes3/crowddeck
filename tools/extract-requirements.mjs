// Extracts the requirement set and acceptance criteria from SPECIFICATION.md into
// docs/data/requirements.json, so the specification document stays the single
// source of truth and the dashboard can never drift from it.
//
//   node tools/extract-requirements.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = join(root, "SPECIFICATION.md");
const outPath = join(root, "docs", "data", "requirements.json");

const lines = readFileSync(specPath, "utf8").split(/\r?\n/);

// Requirements wrap across lines with a two-space continuation indent.
// Unwrap them so each bullet becomes exactly one logical line.
const unwrapped = [];
for (const raw of lines) {
  const isContinuation = /^ {2,}\S/.test(raw) && unwrapped.length > 0 && /^- \*\*REQ-/.test(unwrapped.at(-1));
  if (isContinuation) unwrapped[unwrapped.length - 1] += " " + raw.trim();
  else unwrapped.push(raw);
}

const GROUPS = {
  LIC: { name: "Licence & boundary", adr: "ADR-001" },
  CDEP: { name: "Engine IPC (CDEP)", adr: "ADR-002" },
  SCH: { name: "Unified Scheduler", adr: null },
  POL: { name: "Venue policy", adr: null },
  MODE: { name: "Mode & handoff", adr: null },
  FALL: { name: "Never-silent fallback", adr: null },
  DAT: { name: "Data model", adr: "ADR-003 / ADR-004" },
  API: { name: "Public API", adr: "ADR-005" },
  MIDI: { name: "MIDI & mapping", adr: null },
  CLK: { name: "Clock & sync", adr: null },
  INST: { name: "Instruments as sources", adr: null },
  CON: { name: "Content & ingest", adr: null },
  NFR: { name: "Non-functional", adr: null }
};

// Strip markdown emphasis/code/links down to readable prose.
// Inline capability citations like "(*C1*, *B6*)" are removed because they are
// captured structurally in the `capabilities` field.
function clean(s) {
  return s
    .replace(/\s*\(\s*\*[A-H]\d+\*(?:\s*,\s*\*[A-H]\d+\*)*\s*\)/g, "")
    .replace(/\*([A-H]\d+)\*/g, "$1")
    .replace(/\*\*/g, "")
    .replace(/\*([^*]+)\*/g, "$1")
    .replace(/`/g, "")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

let section = "";
const requirements = [];
const acceptance = [];

for (const line of unwrapped) {
  const h = line.match(/^#{2,3}\s+(.*)$/);
  if (h) section = clean(h[1]);

  const req = line.match(/^- \*\*(REQ-([A-Z]+)-(\d+))\*\*\s+(.*)$/);
  if (req) {
    const [, id, group, num, rawText] = req;
    const text = clean(rawText);
    // RFC 2119 level, taken from the strongest keyword present.
    const level = /\bMUST NOT\b|\bMUST\b/.test(rawText)
      ? "MUST"
      : /\bSHOULD\b/.test(rawText)
        ? "SHOULD"
        : "MAY";
    // Capability IDs cited inline, e.g. (*C1*, *B6*)
    const caps = [...rawText.matchAll(/\*([A-H]\d+)\*/g)].map((m) => m[1]);
    requirements.push({
      id,
      group,
      groupName: GROUPS[group]?.name ?? group,
      adr: GROUPS[group]?.adr ?? null,
      num: Number(num),
      section,
      level,
      capabilities: caps,
      text
    });
  }

  const ac = line.match(/^\|\s*\*\*(AC-\d+)\*\*\s*(\([^)]*\))?\s*\|\s*(.*?)\s*\|\s*$/);
  if (ac) {
    const [, id, capsRaw, body] = ac;
    const caps = capsRaw ? [...capsRaw.matchAll(/\*?([A-H]\d+)\*?/g)].map((m) => m[1]) : [];
    const adrRefs = capsRaw ? [...capsRaw.matchAll(/(ADR-\d+)/g)].map((m) => m[1]) : [];
    const reqRefs = capsRaw ? [...capsRaw.matchAll(/(REQ-[A-Z]+-\d+)/g)].map((m) => m[1]) : [];
    acceptance.push({ id, capabilities: caps, adr: adrRefs, requirements: reqRefs, text: clean(body) });
  }
}

if (!requirements.length) {
  console.error("No requirements found — has SPECIFICATION.md changed format?");
  process.exit(1);
}

const dupes = requirements.map((r) => r.id).filter((id, i, a) => a.indexOf(id) !== i);
if (dupes.length) {
  console.error(`Duplicate requirement IDs: ${[...new Set(dupes)].join(", ")}`);
  process.exit(1);
}

const byGroup = {};
for (const r of requirements) byGroup[r.group] = (byGroup[r.group] || 0) + 1;

const out = {
  generated: new Date().toISOString().slice(0, 10),
  source: "SPECIFICATION.md",
  note: "Generated by tools/extract-requirements.mjs. Do not edit by hand — edit SPECIFICATION.md and re-run.",
  counts: {
    total: requirements.length,
    must: requirements.filter((r) => r.level === "MUST").length,
    should: requirements.filter((r) => r.level === "SHOULD").length,
    acceptance: acceptance.length,
    byGroup
  },
  groups: Object.entries(GROUPS).map(([id, g]) => ({ id, ...g, count: byGroup[id] || 0 })),
  requirements,
  acceptance
};

writeFileSync(outPath, JSON.stringify(out, null, 2), "utf8");
console.log(
  `Extracted ${requirements.length} requirements ` +
    `(${out.counts.must} MUST, ${out.counts.should} SHOULD) ` +
    `and ${acceptance.length} acceptance criteria -> docs/data/requirements.json`
);
